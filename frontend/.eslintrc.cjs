const fs = require('fs');
const path = require('path');

// Cada carpeta de src/features es un módulo aislado: no puede importar de otro feature.
// Las zonas se generan solas, así que al crear un feature nuevo no hay que tocar este archivo.
const featuresDir = path.join(__dirname, 'src/features');
const features = fs.existsSync(featuresDir)
  ? fs
      .readdirSync(featuresDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
  : [];

const crossFeatureZones = features.map((feature) => ({
  target: `./src/features/${feature}`,
  from: './src/features',
  except: [`./${feature}`],
}));

